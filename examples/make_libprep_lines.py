"""Generate a library prep workcell of identical lines (the two-arm demo, scaled up), sized
for about 105 batches of 96 samples (10,000 samples) a day at four lines.

Each line has a prep arm and a capture arm sharing one handoff spot, like
examples/libprep_2arm.yaml. Lines are separate (no handoff between them), so a batch stays on
the line whose storage holds its plates: batch b's plates start in line ((b - 1) % lines) + 1.
(Linking neighbouring lines through handoffs let plates drift across lines and relay through
several arms at once, which cost hours of idle holds; see README.)

    .venv/bin/python examples/make_libprep_lines.py --lines 4 --batches 105 \\
        > examples/libprep_10k.yaml
"""
import argparse

import yaml

# per line; the capture zone holds the 4 h hybridization
PREP = {"thermocycler": 2, "liquid_handler": 2, "heated_shaker": 1}
CAPTURE = {"thermocycler": 7, "liquid_handler": 2, "heated_shaker": 2, "vacuum_concentrator": 2}
SHORT = {"thermocycler": "tc", "liquid_handler": "lh", "heated_shaker": "hs",
         "vacuum_concentrator": "dry"}


def workcell(lines: int, batches: int) -> dict:
    instruments, plates = [], []
    for k in range(1, lines + 1):
        prep = [(f"store{k}", "storage", {"slots": 4000}), (f"hotel{k}a", "hotel", {"slots": 20}),
                (f"scan{k}", "barcode_scanner", {}), (f"stamp{k}", "head_stamper", {}),
                (f"seal{k}", "plate_sealer", {}), (f"peel{k}", "plate_peeler", {}),
                (f"read{k}a", "plate_reader", {})]
        cap = [(f"hotel{k}b", "hotel", {"slots": 20}), (f"spin{k}", "centrifuge", {}),
               (f"read{k}b", "plate_reader", {})]
        for zone, counts, z in ((prep, PREP, "a"), (cap, CAPTURE, "b")):
            zone += [(f"{SHORT[t]}{k}{z}{i}", t, {}) for t, n in counts.items()
                     for i in range(1, n + 1)]
        instruments += [{"id": f"arm{k}a", "type": "arm",
                         "reach": [i for i, _, _ in prep] + [f"ho{k}"]},
                        {"id": f"arm{k}b", "type": "arm",
                         "reach": [i for i, _, _ in cap] + [f"ho{k}"]},
                        {"id": f"ho{k}", "type": "handoff", "slots": 2}]
        instruments += [{"id": i, "type": t, **extra} for i, t, extra in prep + cap]
    kinds = {"G": "gdna", "TAG": "tagmentation_mix", "STP": "stop_buffer",
             "PCR": "pcr_master_mix", "IDX": "index_adapters"}
    for b in range(1, batches + 1):
        home = f"store{(b - 1) % lines + 1}"
        plates += [{"barcode": f"{p}{b:04d}", "type": t, "location": home}
                   for p, t in kinds.items()]
        # new_plate("empty") takes empties in plate order, batch by batch: 4 per batch
        plates += [{"barcode": f"E{4 * (b - 1) + i:04d}", "type": "empty", "location": home}
                   for i in range(1, 5)]
    return {"instruments": instruments, "durations": {"default": 1, "check_status": 0},
            "plates": plates}


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--lines", type=int, default=4)
    ap.add_argument("--batches", type=int, default=105)
    a = ap.parse_args()
    print(f"# Generated by examples/make_libprep_lines.py --lines {a.lines} "
          f"--batches {a.batches}; see that file.")
    print(yaml.safe_dump(workcell(a.lines, a.batches), sort_keys=False, width=100))
